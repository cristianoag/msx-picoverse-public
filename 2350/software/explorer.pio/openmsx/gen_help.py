import re
import sys
from pathlib import Path

here = Path(__file__).resolve().parent
src = Path(sys.argv[1]) if len(sys.argv) > 1 else here.parent / "pico" / "explorer" / "help_text.h"
dst = Path(sys.argv[2]) if len(sys.argv) > 2 else here / "share" / "extensions" / "PicoVerse_2350" / "help.txt"

text = src.read_text(encoding="utf-8")
pages = {}
for match in re.finditer(r"static const char (help(\d+)_\w+)\[\] =(.*?);[ \t]*$", text, re.S | re.M):
    name, columns, body = match.group(1), match.group(2), match.group(3)
    lines = []
    for token in re.finditer(r'HELP_([HL])\("((?:[^"\\]|\\.)*)"\)|"((?:[^"\\]|\\.)*)"', body):
        kind, line, last = token.groups()
        lines.append(("H" if kind == "H" else "L", line if kind else last))
    pages[name] = (columns, lines)

output = ["# Generated by gen_help.py from pico/explorer/help_text.h, do not edit."]
count = None
for columns, table in re.findall(r"help_pages_(\d+)\[HELP_PAGE_COUNT\] = \{(.*?)\};", text, re.S):
    names = re.findall(r"HELP_PAGE\((\w+)\)", table)
    if count not in (None, len(names)):
        sys.exit("the 40 and 80 column help sets have a different number of pages")
    count = len(names)
    for index, name in enumerate(names):
        for kind, line in pages[name][1]:
            output.append(f"{columns} {index} {kind} {line}")
if not count:
    sys.exit(f"{src}: no help pages found")
dst.parent.mkdir(parents=True, exist_ok=True)
dst.write_text("\n".join(output) + "\n", encoding="ascii", newline="\n")
print(f"{dst}: {count} pages, {len(output) - 1} lines")
