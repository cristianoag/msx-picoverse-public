# gen_help.py - Convert the Explorer firmware help pages (pico/explorer/help_text.h)
# into the plain text file read by the openMSX add-on (picoverse2350.tcl), so the
# emulated Pico serves the same F5 help as the cartridge. One line per help line:
# "<columns> <page> H|L <text>" (H = heading), in page order.
